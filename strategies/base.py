class StrategyRegistry:
    """
    Registry for strategy management.

    Tracks all strategies and their performance.
    """

    def __init__(self):
        self.strategies: Dict[str, BaseStrategy] = {}
        self.strategy_history: List[Dict[str, Any]] = []

    def register(self, strategy: BaseStrategy) -> str:
        """Register a strategy."""
        self.strategies[strategy.strategy_id] = strategy
        logger.info(f"Registered strategy: {strategy.config.name} ({strategy.strategy_id})")
        return strategy.strategy_id

    def unregister(self, strategy_id: str) -> bool:
        """Unregister a strategy."""
        if strategy_id in self.strategies:
            strategy = self.strategies[strategy_id]
            strategy.set_status(StrategyStatus.RETIRED)

            # Save history
            self.strategy_history.append(strategy.get_state())

            del self.strategies[strategy_id]
            return True
        return False

    def get(self, strategy_id: str) -> Optional[BaseStrategy]:
        """Get strategy by ID."""
        return self.strategies.get(strategy_id)

    def get_active(self) -> List[BaseStrategy]:
        """Get all active strategies."""
        return [
            s for s in self.strategies.values()
            if s.status in [StrategyStatus.LIVE, StrategyStatus.PAPER]
        ]

    def get_by_status(self, status: StrategyStatus) -> List[BaseStrategy]:
        """Get strategies by status."""
        return [s for s in self.strategies.values() if s.status == status]

    def get_best_performers(
        self,
        metric: str = 'sharpe_ratio',
        top_n: int = 5
    ) -> List[BaseStrategy]:
        """Get top performing strategies."""
        strategies = list(self.strategies.values())
        strategies.sort(
            key=lambda s: getattr(s.metrics, metric, 0),
            reverse=True
        )
        return strategies[:top_n]

    def compare_strategies(self) -> Dict[str, Dict[str, float]]:
        """Compare all strategies by metrics."""
        return {
            s.config.name: s.metrics.to_dict()
            for s in self.strategies.values()
        }


