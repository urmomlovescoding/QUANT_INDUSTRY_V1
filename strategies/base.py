class MomentumStrategy(BaseStrategy):
    """Simple momentum strategy."""

    def __init__(self, config: StrategyConfig = None):
        if config is None:
            config = StrategyConfig(
                name="Momentum Strategy",
                parameters={
                    'lookback': 20,
                    'threshold': 0.02,
                }
            )
        super().__init__(config)

    def generate_signals(
        self,
        data: Dict[str, Any],
        features: Dict[str, np.ndarray] = None,
        regime: str = None
    ) -> List[Signal]:
        signals = []

        for symbol in self.config.symbols or data.keys():
            if symbol not in data:
                continue

            prices = data[symbol].get('close', [])
            if len(prices) < self.config.parameters.get('lookback', 20):
                continue

            lookback = self.config.parameters['lookback']
            threshold = self.config.parameters.get('threshold', 0.02)

            # Calculate momentum
            momentum = (prices[-1] - prices[-lookback]) / prices[-lookback]

            # Generate signal
            if abs(momentum) > threshold:
                direction = SignalDirection.LONG if momentum > 0 else SignalDirection.SHORT
                signal = Signal(
                    strategy_id=self.strategy_id,
                    symbol=symbol,
                    direction=direction,
                    strength=np.tanh(momentum * 10),  # Normalize to [-1, 1]
                    confidence=min(1.0, abs(momentum) / 0.1),
                    entry_price=prices[-1],
                    metadata={'momentum': momentum},
                )
                signals.append(signal)

        return signals


class MeanReversionStrategy(BaseStrategy):
    """Mean reversion strategy."""

    def __init__(self, config: StrategyConfig = None):
        if config is None:
            config = StrategyConfig(
                name="Mean Reversion Strategy",
                parameters={
                    'lookback': 20,
                    'zscore_threshold': 2.0,
                }
            )
        super().__init__(config)

    def generate_signals(
        self,
        data: Dict[str, Any],
        features: Dict[str, np.ndarray] = None,
        regime: str = None
    ) -> List[Signal]:
        signals = []

        for symbol in self.config.symbols or data.keys():
            if symbol not in data:
                continue

            prices = data[symbol].get('close', [])
            lookback = self.config.parameters.get('lookback', 20)

            if len(prices) < lookback:
                continue

            # Calculate z-score
            recent = np.array(prices[-lookback:])
            mean = np.mean(recent)
            std = np.std(recent)

            if std < 1e-8:
                continue

            zscore = (prices[-1] - mean) / std
            threshold = self.config.parameters.get('zscore_threshold', 2.0)

            # Generate signal (opposite to z-score)
            if abs(zscore) > threshold:
                direction = SignalDirection.SHORT if zscore > 0 else SignalDirection.LONG
                signal = Signal(
                    strategy_id=self.strategy_id,
                    symbol=symbol,
                    direction=direction,
                    strength=-np.tanh(zscore / 3),  # Opposite direction
                    confidence=min(1.0, abs(zscore) / 4),
                    entry_price=prices[-1],
                    stop_loss=mean,  # Stop at mean
                    metadata={'zscore': zscore, 'mean': mean, 'std': std},
                )
                signals.append(signal)

        return signals
