class BaseStrategy(ABC):
    """
    Abstract base class for trading strategies.

    Implement generate_signals() for custom strategy logic.
    """

    def __init__(self, config: StrategyConfig = None):
        self.config = config or StrategyConfig()
        self.strategy_id = str(uuid.uuid4())[:8]
        self.status = StrategyStatus.DRAFT

        # State
        self.positions: Dict[str, float] = {}
        self.signals_generated: List[Signal] = []

        # Performance tracking
        self.metrics = StrategyMetrics()
        self.equity_curve: List[float] = []
        self.returns: List[float] = []

        # Callbacks
        self.on_signal: List[Callable[[Signal], None]] = []

    @abstractmethod
    def generate_signals(
        self,
        data: Dict[str, Any],
        features: Dict[str, np.ndarray] = None,
        regime: str = None
    ) -> List[Signal]:
        """
        Generate trading signals.

        Args:
            data: Market data dictionary with OHLCV
            features: Computed features
            regime: Current market regime

        Returns:
            List of Signal objects
        """
        pass

    def initialize(self) -> None:
        """Initialize strategy (called before first run)."""
        pass

    def update(self, data: Dict[str, Any]) -> List[Signal]:
        """
        Update strategy with new data and generate signals.

        Args:
            data: New market data

        Returns:
            List of new signals
        """
        if self.status not in [StrategyStatus.LIVE, StrategyStatus.PAPER, StrategyStatus.BACKTESTING]:
            return []

        signals = self.generate_signals(data)

        for signal in signals:
            signal.strategy_id = self.strategy_id
            self.signals_generated.append(signal)

            # Notify handlers
            for handler in self.on_signal:
                try:
                    handler(signal)
                except Exception as e:
                    logger.error(f"Signal handler error: {e}")

        return signals

    def record_trade_result(
        self,
        signal: Signal,
        entry_price: float,
        exit_price: float,
        pnl: float
    ) -> None:
        """Record trade result for performance tracking."""
        self.returns.append(pnl)
        self.metrics.total_signals += 1

        if pnl > 0:
            self.metrics.winning_signals += 1
            self.metrics.avg_win = (
                (self.metrics.avg_win * (self.metrics.winning_signals - 1) + pnl) /
                self.metrics.winning_signals
            )
        else:
            self.metrics.losing_signals += 1
            self.metrics.avg_loss = (
                (self.metrics.avg_loss * (self.metrics.losing_signals - 1) + abs(pnl)) /
                self.metrics.losing_signals
            ) if self.metrics.losing_signals > 0 else abs(pnl)

        # Update win rate
        if self.metrics.total_signals > 0:
            self.metrics.win_rate = self.metrics.winning_signals / self.metrics.total_signals

        # Update profit factor
        if self.metrics.avg_loss > 0:
            self.metrics.profit_factor = self.metrics.avg_win / self.metrics.avg_loss

        # Update total return
        self.metrics.total_return = sum(self.returns)

        # Update equity curve
        if self.equity_curve:
            self.equity_curve.append(self.equity_curve[-1] + pnl)
        else:
            self.equity_curve.append(pnl)

        # Update drawdown
        self._update_drawdown()

    def _update_drawdown(self) -> None:
        """Update max drawdown metric."""
        if not self.equity_curve:
            return

        equity = np.array(self.equity_curve)
        peak = np.maximum.accumulate(equity)
        drawdown = (peak - equity) / (peak + 1e-8)
        self.metrics.max_drawdown = float(np.max(drawdown))

    def calculate_sharpe(self, risk_free_rate: float = 0.02) -> float:
        """Calculate Sharpe ratio."""
        if len(self.returns) < 2:
            return 0.0

        returns_arr = np.array(self.returns)
        mean_ret = np.mean(returns_arr)
        std_ret = np.std(returns_arr)

        if std_ret < 1e-8:
            return 0.0

        daily_rf = risk_free_rate / 252
        self.metrics.sharpe_ratio = float(np.sqrt(252) * (mean_ret - daily_rf) / std_ret)

        return self.metrics.sharpe_ratio

    def get_state(self) -> Dict[str, Any]:
        """Get strategy state for persistence."""
        return {
            'strategy_id': self.strategy_id,
            'config': {
                'name': self.config.name,
                'version': self.config.version,
                'parameters': self.config.parameters,
            },
            'status': self.status.value,
            'metrics': self.metrics.to_dict(),
            'positions': self.positions.copy(),
            'signals_count': len(self.signals_generated),
        }

    def set_status(self, status: StrategyStatus) -> None:
        """Set strategy status."""
        old_status = self.status
        self.status = status
        logger.info(f"Strategy {self.config.name}: {old_status.value} -> {status.value}")


